#!/usr/bin/env python3
"""Freeze novel authored sources, infer locally, and expose model ON/OFF/raw arms.

No human target exists, so coordinate MAE is deliberately null. Sources are
independently authored and never generated by the engine under evaluation.
"""
from pathlib import Path
from hashlib import sha256
from copy import deepcopy
import argparse, json, os, sys, html
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def fixtures():
    return {f'authored:{p.stem}': json.loads(p.read_text()) for p in
            sorted((ROOT/'tests/fixtures/novel_level3_sources').glob('n*.json'))}


def run(args):
    from scripts.evaluate_qwen_adapter import run_engine_mode, summarize_engine
    from scripts.layout_defects import assess_engine_layout
    from engine.resize import _adapt_with_diagnostics
    from scripts.build_diverse_dataset_viewer import proposal_design
    from engine.qwen_prompt import messages_for
    from transformers import AutoTokenizer
    args.output.mkdir(parents=True, exist_ok=True)
    sources = fixtures()
    records = [dict(pair_id=f'{key}__to__{t["name"]}', family_id=key,
                    source_split='train', target_canvas={k: t[k] for k in ('width', 'height')})
               for key, fixture in sources.items() for t in fixture['targets']]
    tracked = ['engine/resize.py','engine/qwen_seed.py','engine/qwen_prompt.py',
               'engine/qwen_refine.py','engine/source_structure.py','engine/layout_contracts.py',
               'engine/structural_reflow.py','engine/clean_zones.py','scripts/layout_defects.py']
    tokenizer = AutoTokenizer.from_pretrained(str(args.model_dir), local_files_only=True)
    counts = {}
    for r in records:
        source = sources[r['family_id']]['source']
        prompt = tokenizer.apply_chat_template(messages_for(source, r['target_canvas'], version=2),
                    tokenize=False, add_generation_prompt=True, enable_thinking=False)
        counts[r['pair_id']] = len(tokenizer(prompt)['input_ids'])
    manifest = dict(fresh_model_inference=True, sources_sha256={p.name:sha256(p.read_bytes()).hexdigest()
                    for p in sorted((ROOT/'tests/fixtures/novel_level3_sources').glob('n*.json'))},
                    code_sha256={p:sha256((ROOT/p).read_bytes()).hexdigest() for p in tracked},
                    adapter_dir=str(args.adapter_dir), model_dir=str(args.model_dir),
                    adapter_sha256=sha256((args.adapter_dir/'adapter_model.safetensors').read_bytes()).hexdigest(),
                    prompt_tokens=counts, records=records,
                    provenance='Novel authored layouts, text and neutral IDs; unmodified existing training-split photos. Not official samples. No human targets or training records.')
    target = args.output/'run_manifest.json'
    if target.exists() and json.loads(target.read_text()) != manifest:
        raise SystemExit('Inputs, model or code changed; choose a new output directory.')
    target.write_text(json.dumps(manifest, indent=2)+'\n')
    if args.prepare:
        print(json.dumps(dict(cases=len(records), prompt_tokens=counts),indent=2));return
    get = lambda split, key: deepcopy(sources[key]['source'])
    rows = run_engine_mode(records, get, args.adapter_dir, args.model_dir, args.output/'inference.jsonl')
    off_path = args.output/'qwen_off.jsonl'
    cached = {r['pair_id']:r for r in map(json.loads,off_path.read_text().splitlines())} if off_path.exists() else {}
    os.environ['MAGICANVAS_DATASET_RENDERING']='1'
    os.environ['MAGICANVAS_QWEN_ENABLED']='0'
    for row in rows:
        # No human target: do not accidentally measure against the unresized source.
        for key in ('geometry_mae','font_mae','raw_geometry_mae','raw_relative_font_mae'):
            row[key] = None
        if row.get('engine_error'):continue
        source = row['source_design']
        raw = proposal_design(source, row['target_canvas'], row.get('qwen_model_elements') or [])
        row['raw_defects'] = assess_engine_layout(source,raw,{}) if raw['elements'] else {'defect_flags':['no_complete_proposal']}
        if row['pair_id'] in cached:
            off = cached[row['pair_id']]
        else:
            design, diag = _adapt_with_diagnostics(source,row['target_canvas'])
            off = dict(pair_id=row['pair_id'],output_design=design,winner=diag.get('winner'),
                       **assess_engine_layout(source,design,diag))
            with off_path.open('a') as stream:stream.write(json.dumps(off)+'\n')
        row['qwen_off'] = off
        print(row['pair_id'], 'ON',row['winner'],row['defect_flags'],'OFF',off['winner'],off['defect_flags'],flush=True)
    report=dict(summary=summarize_engine(rows),results=rows,manifest=manifest,
                human_target_available=False,fresh_model_inference=True)
    (args.output/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    # The public checkpoint also must never contain spurious raw MAE against source geometry.
    (args.output/'inference.jsonl').write_text(''.join(json.dumps({k:v for k,v in r.items() if k not in ('raw_defects','qwen_off')})+'\n' for r in rows))
    build_viewer(report,args.output)
    print(json.dumps(report['summary'],indent=2))


def build_viewer(report,output):
    from scripts.dataset_renderer import render_design_to_png
    from scripts.build_diverse_dataset_viewer import proposal_design
    from PIL import Image, ImageDraw, ImageOps
    entries=[];cards=[];sources=fixtures()
    for i,row in enumerate(report['results'],1):
        if row.get('engine_error'):
            cards.append(f'<article><h2>{html.escape(row["pair_id"])}</h2><pre>{html.escape(row["engine_error"])}</pre></article>');continue
        source=row['source_design'];key=row['pair_id'].split('__to__')[0]
        entry={k:row.get(k) for k in ('pair_id','winner','defect_flags','qwen_family_win','raw_json_complete','raw_proposal_valid','qwen_status')}
        entry.update(title=sources[key]['title'],qwen_off_winner=row['qwen_off']['winner'],
                     raw_defect_flags=row['raw_defects']['defect_flags'],qwen_off_flags=row['qwen_off']['defect_flags'])
        docs=dict(source=source, raw=proposal_design(source,row['target_canvas'],row.get('qwen_model_elements') or []),
                  output=row['output_design'],off=row['qwen_off']['output_design'])
        sheet=Image.new('RGB',(1400,1100),'#182532');draw=ImageDraw.Draw(sheet)
        for j,(kind,label) in enumerate([('source','Authored source'),('raw','Decoded Qwen / before layout repair'),
                                         ('output','Engine / Qwen ON'),('off','Engine / Qwen OFF')]):
            name=f'{i:02d}_{kind}';png=output/(name+'.png')
            if docs[kind]['elements']:
                render_design_to_png(docs[kind],ROOT/'data/crello_train',png,ROOT/'data/crello_fonts.pickle',max_size=1200,adjust_tight_text_widths=False)
            else:Image.new('RGB',(500,500),'white').save(png)
            jpg=png.with_suffix('.jpg')
            with Image.open(png) as im:
                im.convert('RGB').save(jpg,quality=90,optimize=True)
                tile=ImageOps.contain(im.convert('RGB'),(670,500));sheet.paste(tile,((j%2)*700+(700-tile.width)//2,(j//2)*550+35+(500-tile.height)//2))
            png.unlink();draw.text(((j%2)*700+15,(j//2)*550+10),label,fill='white')
            (output/(name+'.json')).write_text(json.dumps(docs[kind],indent=2)+'\n');entry[kind]=jpg.name;entry[kind+'_json']=name+'.json'
        entry['contact']=f'{i:02d}_contact.jpg';sheet.save(output/entry['contact'],quality=87,optimize=True)
        entries.append(entry)
        cards.append(f'<article><h2>{html.escape(entry["title"])} · {html.escape(row["pair_id"].split("__to__")[1])}</h2><a href="{entry["contact"]}"><img src="{entry["contact"]}"></a><p>Qwen ON: {html.escape(row["winner"])} · learned-family winner: {row["qwen_family_win"]}</p><p>Raw IDs valid: {row['raw_proposal_valid']} · ON flags: {html.escape(str(row["defect_flags"]))} · Raw flags: {html.escape(str(entry["raw_defect_flags"]))} · OFF flags: {html.escape(str(entry["qwen_off_flags"]))}</p><p><a href="{entry["source"]}">Source image</a> · <a href="{entry["raw"]}">Raw image</a> · <a href="{entry["output"]}">ON image</a> · <a href="{entry["off"]}">OFF image</a> · <a href="{entry["source_json"]}">Source JSON</a> · <a href="{entry["raw_json"]}">Raw proposal</a> · <a href="{entry["output_json"]}">Qwen ON JSON</a> · <a href="{entry["off_json"]}">Qwen OFF JSON</a></p></article>')
    (output/'manifest.json').write_text(json.dumps(entries,indent=2)+'\n')
    inference_note='Actual earlier local inference, with the exact decoded coordinates replayed through the current engine.' if not report.get('fresh_model_inference') else 'Fresh local inference with the installed adapter.'
    (output/'index.html').write_text('<!doctype html><meta charset="utf-8"><title>New designs · model ON/OFF</title><style>body{font:17px system-ui;background:#101820;color:#eee;margin:24px}a{color:#9ed4ff}article{background:#182532;padding:20px;margin-bottom:24px;border-radius:12px}img{width:100%;max-width:1400px}p{overflow-wrap:anywhere}</style><h1>New designs · raw model and current engine</h1><p>'+inference_note+' </p><p>Four newly authored sources, 21–23 elements each, two target formats each. Different content, photographs, composition and neutral IDs. Sources frozen before inference; no resized target reference. Photos come from the existing Crello training asset pool, so this is a new-composition stress test, not proof of unseen-asset generalization. The raw, repaired and Qwen-disabled arms expose when deterministic fallback does the work. Every output is retained, including failures. Missing raw IDs remain missing in the raw panel. Later engine recovery, when needed, is disclosed in the JSON status. No training was performed.</p>'+''.join(cards))


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,required=True);p.add_argument('--prepare',action='store_true');p.add_argument('--viewer-only',action='store_true')
    p.add_argument('--adapter-dir',type=Path,default=ROOT/'models/qwen3-layout-lora-v2')
    p.add_argument('--model-dir',type=Path,default=ROOT/'models/qwen3-0.6b')
    a=p.parse_args()
    if a.viewer_only:build_viewer(json.loads((a.output/'report.json').read_text()),a.output)
    else:run(a)
if __name__=='__main__':main()
